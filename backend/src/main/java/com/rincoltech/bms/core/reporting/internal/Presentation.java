package com.rincoltech.bms.core.reporting.internal;

import com.rincoltech.bms.core.reporting.ReportDefinition;
import com.rincoltech.bms.core.reporting.ReportDefinition.Param;
import com.rincoltech.bms.core.tenancy.Letterheads;
import java.time.LocalDate;
import java.time.ZoneId;
import java.time.format.DateTimeParseException;
import java.util.ArrayList;
import java.util.Base64;
import java.util.Collection;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * What the PDF and the workbook say around the figures, read once before rendering (FR-RPT-02): who asked, in whose time
 * zone, under which letterhead, and the parameters in words. It is built from stored values only, so rendering needs no
 * database connection.
 *
 * @param by the requester's name, printed in the "generated by" line (the file is theirs; it is never logged)
 * @param zone the tenant's time zone: the business date and every printed time are in it
 * @param businessName the tenant's display name
 * @param brand {@code #RRGGBB}, the tenant's brand colour or the platform default
 * @param onBrand {@code #RRGGBB}, readable text on {@code brand}
 * @param tint a pale tint of the brand colour for alternate rows
 * @param footer the tenant's footer text
 * @param logo a {@code data:} URI of the logo, or null
 * @param scope the branches in words, for the letterhead's second line ("All branches you may see")
 * @param parameters the run's parameters in words, in the order the report declares them
 */
record Presentation(
        String by,
        ZoneId zone,
        String businessName,
        String brand,
        String onBrand,
        String tint,
        String footer,
        String logo,
        String scope,
        List<Line> parameters) {

    // JUSTIFICATION-A3: new file of this slice (issue #217); no existing code builds the presentation of a report.

    /** The presentation of a run from the tenant's letterhead and what the run stored. */
    static Presentation of(
            Letterheads.Letterhead lh,
            String by,
            ZoneId zone,
            ReportDefinition def,
            Map<String, Object> params,
            String frozenScope) {
        String scope = frozenScope != null ? frozenScope : scope(params);
        List<Line> lines = new ArrayList<>();
        lines.add(new Line("Scope", scope));
        lines.addAll(describe(def, params));
        return new Presentation(
                by,
                zone,
                lh.displayName(),
                lh.brandColour(),
                lh.textOnBrand(),
                tint(lh.brandColour()),
                lh.receiptFooter(),
                lh.logo()
                        .map(l -> "data:" + l.contentType() + ";base64,"
                                + Base64.getEncoder().encodeToString(l.bytes()))
                        .orElse(null),
                scope,
                lines);
    }

    /** A pale tint of the brand colour for alternate table rows: 88% white over it (as the other documents do). */
    static String tint(String hex) {
        int rgb = Integer.parseInt(hex.substring(1), 16);
        StringBuilder out = new StringBuilder("#");
        for (int shift = 16; shift >= 0; shift -= 8) {
            int v = (rgb >> shift) & 0xFF;
            out.append(String.format("%02X", Math.round(v + (255 - v) * 0.88f)));
        }
        return out.toString();
    }

    /** One label and value, for the parameters box and the Parameters sheet. */
    record Line(String label, String value) {}

    /**
     * The run's parameters in words: dates as {@code 8 Oct 2026}, a list of ids as a count (the ids are in the run and
     * in the JSON and CSV), an enum as a word, and a list that was not given as "All" (FR-RPT-02).
     */
    static List<Line> describe(ReportDefinition def, Map<String, Object> params) {
        List<Line> lines = new ArrayList<>();
        for (Param p : def.params()) {
            Object value = params.get(p.name());
            if (p.name().equals("as_at")) {
                // The date the figures stand at has its own line on the page and its own row in the workbook.
                continue;
            }
            String label = ReportFormats.label(p.name(), p.type());
            if (value == null) {
                continue;
            }
            lines.add(new Line(label, text(p, value)));
        }
        return lines;
    }

    /** The branches the report covers, in words. */
    static String scope(Map<String, Object> params) {
        Object branches = params.get("branch_id");
        if (branches instanceof Collection<?> c && !c.isEmpty()) {
            return c.size() == 1 ? "1 branch selected" : c.size() + " branches selected";
        }
        return "All branches in your access";
    }

    private static String text(Param p, Object value) {
        if (value instanceof Collection<?> c) {
            return c.size() + " selected";
        }
        String raw = String.valueOf(value);
        if (p.type().equals("date")) {
            try {
                return ReportFormats.date(LocalDate.parse(raw));
            } catch (DateTimeParseException e) {
                return raw;
            }
        }
        if (p.type().equals("enum") && !raw.isEmpty()) {
            return raw.substring(0, 1).toUpperCase(Locale.ENGLISH)
                    + raw.substring(1).replace('_', ' ');
        }
        return raw;
    }

    /** {@code #RRGGBB} without the hash, for a spreadsheet's ARGB colour. */
    static String hex(String colour) {
        return colour.startsWith("#") ? colour.substring(1) : colour;
    }
}
